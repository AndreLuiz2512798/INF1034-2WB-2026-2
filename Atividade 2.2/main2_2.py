from turtle import *
from time import sleep

t = Turtle()

def retangulo(base, altura, cor):
    t.fillcolor(cor)
    t.begin_fill()
    for count in range(0, 2):
        t.forward(base)
        t.left(90)
        t.fd(altura)
        t.lt(90)
    t.end_fill()

def circulo(raio, cor):
    t.fillcolor(cor)
    t.begin_fill()
    t.circle(raio)
    t.end_fill()

def estrela(lado, cor):
    t.fillcolor(cor)
    t.begin_fill()
    for count in range(0, 5):
        t.forward(lado)
        t.right(144)
        t.fd(lado)
        t.left(72)
    t.end_fill()

